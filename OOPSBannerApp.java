/**
 * OOPS Banner Application
 *
 * UC3: Display "OOPS" banner using String.join()
 * to avoid inefficient string concatenation.
 *
 * @version 3.0
 */
public class OOPSBannerApp {

    public static void main(String[] args) {

        System.out.println(String.join("",
                " *****  ",
                " *****  ",
                " ****** ",
                " *****  "
        ));

        System.out.println(String.join("",
                "*     * ",
                "*     * ",
                "*       ",
                "*     * "
        ));

        System.out.println(String.join("",
                "*     * ",
                "*     * ",
                "*       ",
                "*       "
        ));

        System.out.println(String.join("",
                "*     * ",
                "*     * ",
                " ****** ",
                " *****  "
        ));

        System.out.println(String.join("",
                "*     * ",
                "*     * ",
                "*       ",
                "      * "
        ));

        System.out.println(String.join("",
                "*     * ",
                "*     * ",
                "*       ",
                "*     * "
        ));

        System.out.println(String.join("",
                " *****  ",
                " *****  ",
                " *       ",
                " *****  "
        ));
    }
}
